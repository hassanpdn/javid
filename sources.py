@router.get("/sources/{app}")
def sources(app: str, request: Request):
    """The data map of one assistant, for the permanent account only."""
    access._admin(request)
    if app not in CATALOG:
        raise HTTPException(status_code=404)
    names = {i["key"]: i["name"] for i in CATALOG[app]["items"]}
    items = [i | ({"way_text": WAYS[i["way"]]} if i["kind"] == "raw" else {"made_of_text": [names.get(k, k) for k in i["made_of"]]}) for i in CATALOG[app]["items"]]
    return {"app": app, "title": CATALOG[app]["title"], "ways": WAYS, "items": items}
